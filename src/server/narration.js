// AI 房主的台词：极乐迪斯科式的旁白。不用大模型，每个场合准备几句，轮着用。
// 只说公开的事（谁死了、谁被提名、票数），不碰任何秘密信息。
// 每条返回 { title?, text }：title 有值的会在客户端弹出过场标题卡；text 会被语音读出来。

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const cnDay = (n) => ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'][n] ?? String(n);

const LINES = {
  start: ({ n, script }) => (script === 'bmr' ? {
    title: '黯月驿站',
    text: pick([
      `${n} 个旅人在天黑前赶到了驿站。旅店的炉火很暖，林子里的狼嚎很近。`,
      `枫叶红得发黑。${n} 个人推开黯月旅店的门——今晚的月亮不对劲。`,
      `冬天就要来了。${n} 个人围着炉火喝热茶，谁也没注意窗外那双眼睛。`,
    ]),
  } : {
    title: '钟楼镇',
    text: pick([
      `${n} 个人走进了钟楼镇。镇子很冷，钟声很远。你们之中，有人不是人。`,
      `${n} 张脸，${n} 个故事。其中几个是假的。钟楼在看着。`,
      `雪落在钟楼镇的石板路上。${n} 个人来到这里——不是所有人都能活着离开。`,
    ]),
  }),
  night: ({ night }) => ({
    title: `第${cnDay(night)}夜`,
    text: pick([
      '天黑了。闭上眼睛。有些人会在黑暗里醒来，做他们必须做的事。',
      '钟敲了十二下。整座镇子都睡了——几乎是整座。',
      '夜色像潮水一样漫过屋顶。闭上眼睛，别出声。',
      '灯一盏一盏熄灭。现在，轮到黑暗说话了。',
    ]),
  }),
  dawn: ({ day, deaths, script }) => ({
    title: `第${cnDay(day)}天`,
    text: deaths.length
      ? pick([
        `天亮了。昨晚，${deaths.join('、')}没能醒来。${script === 'bmr' ? '落叶上没有脚印。' : '雪地上没有脚印。'}`,
        `清晨的钟声里少了一个人的呼吸。${deaths.join('、')}死了。`,
        `太阳照常升起，可${deaths.join('、')}再也看不到了。有人知道为什么。`,
      ])
      : pick([
        '天亮了。昨晚是平安夜——每个人都醒了过来。这比死人更让人不安。',
        '清晨。所有人都还活着。恶魔今晚没有动手……或者它动了手，却失败了。',
      ]),
  }),
  roam: ({ minutes }) => ({
    text: pick([
      `去走走吧。敲开一扇门，和谁说几句悄悄话。${minutes ? `${cnDay(minutes)}分钟后钟声会把你们叫回来。` : ''}`,
      `街道是空的，房子是暖的。去找你信得过的人——如果还有的话。${minutes ? `${cnDay(minutes)}分钟。` : ''}`,
    ]),
  }),
  roamSoon: () => ({
    text: pick([
      '天色暗下来了。还有三十秒，钟声就要响了。',
      '远处的钟楼开始准备了。再过半分钟，所有人都要回到广场。',
    ]),
  }),
  gather: () => ({
    text: pick([
      '钟声响了。所有人回到广场。',
      '当——当——当。回到广场来，该做决定了。',
    ]),
  }),
  nomOpen: ({ minutes }) => ({
    text: pick([
      `广场上很安静。谁有话要说？现在可以提名了，${cnDay(minutes)}分钟。`,
      `指着一个人，说出你的怀疑。提名开始，你们有${cnDay(minutes)}分钟。`,
    ]),
  }),
  nomRemind: () => ({ text: pick(['还剩一分钟。天快黑了。', '一分钟。犹豫的人，夜里会后悔。']) }),
  nominate: ({ a, b }) => ({
    text: pick([
      `${a}站了出来，手指向${b}。`,
      `${a}提名了${b}。广场上的人都转过头去。`,
      `"是你。"${a}看着${b}说。`,
    ]),
  }),
  accuse: ({ a }) => ({ text: `${a}，说出你的理由。` }),
  defend: ({ b }) => ({ text: pick([`${b}，为自己辩护吧。`, `轮到${b}了。说服他们。`]) }),
  voteStart: ({ b }) => ({ text: pick([`投票。想处决${b}的人，举起手。`, `举手。指针会一个一个经过你们。`]) }),
  vote: ({ b, count, need, outcome }) => ({
    text: {
      block: pick([`${count}票。${b}被送上了处决台。`, `${count}只手举了起来。${b}站上处决台，脸色苍白。`]),
      tie: `${count}票，平票。处决台空了出来。`,
      lower: `${count}票。不够把台上的人换下来。`,
      fail: pick([`${count}票，需要${need}票。${b}逃过了这一次。`, `只有${count}只手。${b}松了一口气。`]),
    }[outcome],
  }),
  execution: ({ name }) => ({
    title: '处决',
    text: pick([
      `黄昏。${name}被处决了。绳子拉紧，然后一切都安静了。`,
      `广场上的人看着${name}倒下。没有人说话。`,
      `${name}被处决了。这是正义，还是又一个错误？`,
    ]),
  }),
  noExecution: ({ already }) => ({
    text: already ? '黄昏。今天的血已经流过了。' : pick(['黄昏。今天没有人被处决。镇民们各自回家，锁好门。', '黄昏来了，处决台是空的。今晚，谁会后悔？']),
  }),
  virgin: ({ a }) => ({
    title: '处决',
    text: `一道白光。${a}还没来得及收回手指，就倒在了贞洁者面前。`,
  }),
  // 造谣者式的公开声明：原话照念，所有人都听得到、看得到（官方规则要求声明必须公开）
  gossip: ({ a, text }) => ({
    title: '公开声明',
    text: `${a}站了出来，当众说：「${text}」`,
  }),
  slay: ({ a, b, hit }) => ({
    title: '开枪',
    text: hit
      ? `${a}举起枪，扣下扳机。${b}倒下了——那张人皮下面，是别的东西。`
      : pick([`${a}朝${b}开了一枪。什么都没有发生。`, `枪声在广场上回荡。${b}还站着。`]),
  }),
  end: ({ team, reason, script }) => (script === 'bmr' ? {
    title: team === 'good' ? '善良获胜' : '邪恶获胜',
    text: team === 'good'
      ? pick([`${reason}。月亮落下去了，驿站的炉火还亮着。`, `${reason}。林子里的狼嚎停了。`])
      : pick([`${reason}。黯月高悬，驿站再也没有旅人醒来。`, `${reason}。最后一盏油灯熄灭了。`]),
  } : {
    title: team === 'good' ? '善良获胜' : '邪恶获胜',
    text: team === 'good'
      ? pick([`${reason}。钟楼镇的天终于亮了。`, `${reason}。恶魔的笑声停了，雪还在下。`])
      : pick([`${reason}。钟楼镇陷入了永夜。`, `${reason}。最后的灯熄灭了。`]),
  }),
};

/** 某个场合的一句旁白。 */
export function narration(event, vars = {}) {
  return LINES[event]?.(vars) ?? null;
}
